/// Индекс в [readableTaskLessons] для карточки с тем же порядком, что в сетке.
int readableLessonIndex(int dailyIndex) {
  var page = 0;
  for (var i = 0; i < dailyIndex && i < taskLessons.length; i++) {
    if (!taskLessons[i].premium) page++;
  }
  return page;
}
